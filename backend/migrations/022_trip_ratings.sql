-- A passenger rates a trip they paid for: 1 to 5 stars and an optional comment, seen only by the SACCO office.
-- The car, its driver and the conductor are kept as they were when the rating was given (trips don't record the driver).
CREATE TABLE trip_ratings (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id      INTEGER NOT NULL UNIQUE REFERENCES trips(id),
  passenger_id INTEGER NOT NULL REFERENCES users(id),
  vehicle_id   INTEGER NOT NULL REFERENCES vehicles(id),
  driver_id    INTEGER REFERENCES users(id),
  conductor_id INTEGER REFERENCES users(id),
  stars        INTEGER NOT NULL CHECK (stars BETWEEN 1 AND 5),
  comment      TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX trip_ratings_vehicle ON trip_ratings (vehicle_id, id);
CREATE INDEX trip_ratings_id ON trip_ratings (id);
