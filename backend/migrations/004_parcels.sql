-- Parcels: the office records a parcel at the counter, the sender pays the fee (SACCO income, kept apart from
-- fares and passenger wallets), a car carries it, and the receiver collects it with a secret code.

CREATE TABLE parcels (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Given to the sender and receiver: anyone with it can follow the parcel on the website.
  tracking_code     TEXT NOT NULL UNIQUE,
  -- Only for the receiver: shown when collecting. Never shown on the website.
  collection_code   TEXT NOT NULL,
  sender_name       TEXT NOT NULL,
  sender_phone      TEXT NOT NULL,
  receiver_name     TEXT NOT NULL,
  receiver_phone    TEXT NOT NULL,
  route_id          INTEGER NOT NULL REFERENCES routes(id),
  stop_id           INTEGER NOT NULL REFERENCES route_stops(id),
  description       TEXT,
  fee               INTEGER NOT NULL CHECK (fee > 0),
  status            TEXT NOT NULL DEFAULT 'awaiting_payment'
                    CHECK (status IN ('awaiting_payment', 'received', 'on_the_way', 'arrived', 'collected', 'cancelled')),
  -- How the fee was paid: the PIN prompt, an M-Pesa code the clerk typed in, or cash.
  payment_method    TEXT CHECK (payment_method IN ('mpesa_prompt', 'mpesa_code', 'cash')),
  payment_reference TEXT,
  paid_at           TIMESTAMPTZ,
  vehicle_id        INTEGER REFERENCES vehicles(id),
  load_id           INTEGER REFERENCES loads(id),
  created_by        INTEGER NOT NULL REFERENCES users(id),
  collected_by      INTEGER REFERENCES users(id),
  cancel_reason     TEXT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  loaded_at         TIMESTAMPTZ,
  arrived_at        TIMESTAMPTZ,
  collected_at      TIMESTAMPTZ,
  cancelled_at      TIMESTAMPTZ
);
CREATE INDEX idx_parcels_status_route ON parcels (status, route_id);
CREATE INDEX idx_parcels_vehicle ON parcels (vehicle_id, status);

-- PIN prompts for parcel fees. Like mpesa_payments, but the money is the SACCO's, never a passenger's wallet.
CREATE TABLE parcel_payments (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parcel_id           INTEGER NOT NULL REFERENCES parcels(id),
  phone               TEXT NOT NULL,
  amount              INTEGER NOT NULL CHECK (amount > 0),
  status              TEXT NOT NULL CHECK (status IN ('initiating', 'pending', 'completed', 'failed')),
  checkout_request_id TEXT UNIQUE,
  merchant_request_id TEXT,
  mpesa_receipt       TEXT UNIQUE,
  result_desc         TEXT,
  last_queried_at     TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at        TIMESTAMPTZ
);
CREATE INDEX idx_parcel_payments_status ON parcel_payments (status);
