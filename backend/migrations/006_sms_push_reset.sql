-- SMS, push notifications and "forgot password".

-- Texts waiting to be sent, and what happened to each. Queued inside the same transaction as the change they are
-- about, and sent only once it is saved. The text is removed once sent (it can hold a code).
CREATE TABLE sms_outbox (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone               TEXT NOT NULL,
  kind                TEXT NOT NULL,
  message             TEXT,
  status              TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'sent', 'failed', 'logged')),
  provider_message_id TEXT,
  error               TEXT,
  attempts            INTEGER NOT NULL DEFAULT 0,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  sent_at             TIMESTAMPTZ
);
CREATE INDEX idx_sms_outbox_status ON sms_outbox (status, created_at);

-- The phones that receive push notifications for a user (Expo push tokens).
CREATE TABLE push_tokens (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER NOT NULL REFERENCES users(id),
  token        TEXT NOT NULL UNIQUE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_push_tokens_user ON push_tokens (user_id);

-- When a notification was sent as a push (NULL = not yet).
ALTER TABLE notifications ADD COLUMN pushed_at TIMESTAMPTZ;

-- "Forgot password" codes sent by SMS. Only a hash of the code is kept; it works once, for 10 minutes, 5 tries.
CREATE TABLE password_resets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id),
  code_hash  TEXT NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  attempts   INTEGER NOT NULL DEFAULT 0,
  used_at    TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_password_resets_user ON password_resets (user_id, created_at);
