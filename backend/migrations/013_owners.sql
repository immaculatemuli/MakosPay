-- Vehicle owners set up once (one person can own many cars), instead of typed on every vehicle. Each vehicle links
-- to its owner; the owner's name, phone and payout details are copied onto the vehicle (and onto each fare, for the
-- record) so a change on the owner reaches all their cars. Payouts remember the owner they went to.
CREATE TABLE owners (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           TEXT NOT NULL,
  phone          TEXT NOT NULL UNIQUE,
  id_number      TEXT,
  payout_method  TEXT NOT NULL DEFAULT 'mpesa' CHECK (payout_method IN ('mpesa', 'bank')),
  bank_name      TEXT,
  bank_paybill   TEXT,
  bank_account   TEXT,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE vehicles ADD COLUMN owner_id INTEGER REFERENCES owners(id);
ALTER TABLE payouts ADD COLUMN owner_id INTEGER REFERENCES owners(id);
CREATE INDEX idx_vehicles_owner ON vehicles (owner_id);
CREATE INDEX idx_trips_owner_unpaid ON trips (owner_phone) WHERE payout_id IS NULL;

-- One owner per phone number already on vehicles, with the details of their most recently added vehicle.
INSERT INTO owners (name, phone, payout_method, bank_name, bank_paybill, bank_account)
SELECT v.owner_name, v.owner_phone, v.owner_payout_method, v.owner_bank_name, v.owner_bank_paybill, v.owner_bank_account
FROM vehicles v WHERE v.id = (SELECT MAX(v2.id) FROM vehicles v2 WHERE v2.owner_phone = v.owner_phone);
UPDATE vehicles SET owner_id = (SELECT o.id FROM owners o WHERE o.phone = vehicles.owner_phone);
UPDATE payouts SET owner_id = (SELECT o.id FROM owners o WHERE o.phone = payouts.owner_phone);
