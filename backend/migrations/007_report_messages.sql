-- Problem reports become a conversation: after the first message (reports.message), the reporter and the SACCO
-- office can keep replying. Each reply is one row here.
CREATE TABLE report_messages (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id   INTEGER NOT NULL REFERENCES reports(id),
  -- Who wrote it (NULL only for office replies written before this table, when nobody was recorded).
  sender_id   INTEGER REFERENCES users(id),
  from_office BOOLEAN NOT NULL,
  message     TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_report_messages_report ON report_messages (report_id, id);

-- The office's single reply from before becomes the first reply of the conversation.
INSERT INTO report_messages (report_id, sender_id, from_office, message, created_at)
SELECT id, handled_by, TRUE, office_note, updated_at FROM reports WHERE office_note IS NOT NULL;
