-- A conductor or driver asks the office to refund a fare paid on their car by mistake (wrong car, paid twice...).
-- The office refunds it (the usual fare refund) or says no. Only one request per payment can be waiting at a time.
CREATE TABLE refund_requests (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id      INTEGER NOT NULL REFERENCES trips(id),
  requested_by INTEGER NOT NULL REFERENCES users(id),
  reason       TEXT NOT NULL,
  status       TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'refunded', 'declined')),
  office_note  TEXT,
  decided_by   INTEGER REFERENCES users(id),
  decided_at   TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX refund_requests_one_waiting ON refund_requests (trip_id) WHERE status = 'waiting';
CREATE INDEX refund_requests_status ON refund_requests (status, id);
