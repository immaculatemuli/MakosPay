-- Seat booking from anywhere: a passenger pays for seats on a route and joins the queue at its stage (or asks to be
-- picked on the road); the stage marshal fills each car that arrives from the queue, first booked first served.
-- Paid money is held in the passenger's wallet history (booking_hold) until they board, when it is released and paid
-- as a fare on the car they boarded (so its owner is paid); a cancelled booking is released and refunded.

ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check
  CHECK (role IN ('admin', 'passenger', 'conductor', 'driver', 'platform_admin', 'marshal'));

ALTER TABLE wallet_transactions DROP CONSTRAINT IF EXISTS wallet_transactions_type_check;
ALTER TABLE wallet_transactions ADD CONSTRAINT wallet_transactions_type_check
  CHECK (type IN ('topup', 'fare', 'refund', 'test_credit', 'withdrawal', 'withdrawal_reversal', 'booking_hold', 'booking_release'));

ALTER TABLE mpesa_payments DROP CONSTRAINT IF EXISTS mpesa_payments_purpose_check;
ALTER TABLE mpesa_payments ADD CONSTRAINT mpesa_payments_purpose_check CHECK (purpose IN ('wallet', 'fare', 'seat'));

CREATE TABLE seat_bookings (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code               TEXT NOT NULL UNIQUE,
  passenger_id       INTEGER NOT NULL REFERENCES users(id),
  route_id           INTEGER NOT NULL REFERENCES routes(id),
  -- Where the passenger is picked: NULL = at the route's stage, else a stop on the road.
  pickup_stop_id     INTEGER REFERENCES route_stops(id),
  stop_id            INTEGER NOT NULL REFERENCES route_stops(id),
  seats              INTEGER NOT NULL CHECK (seats BETWEEN 1 AND 10),
  fare_each          INTEGER NOT NULL CHECK (fare_each > 0),
  amount             INTEGER NOT NULL CHECK (amount > 0),
  pay_with           TEXT NOT NULL CHECK (pay_with IN ('mpesa', 'wallet')),
  mpesa_payment_id   INTEGER REFERENCES mpesa_payments(id),
  status             TEXT NOT NULL CHECK (status IN ('paying', 'queued', 'assigned', 'boarded', 'cancelled', 'failed')),
  -- Place in the queue: when it was paid (kept if the passenger misses a car, so they stay at the front).
  queued_at          TIMESTAMPTZ,
  load_id            INTEGER REFERENCES loads(id),
  assigned_at        TIMESTAMPTZ,
  passenger_here_at  TIMESTAMPTZ,
  boarded_at         TIMESTAMPTZ,
  trip_id            INTEGER REFERENCES trips(id),
  cancelled_at       TIMESTAMPTZ,
  cancel_reason      TEXT,
  refund_to          TEXT CHECK (refund_to IN ('mpesa', 'wallet')),
  refund_withdrawal_id INTEGER REFERENCES withdrawals(id),
  idempotency_key    TEXT NOT NULL,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (passenger_id, idempotency_key)
);
CREATE INDEX idx_seat_bookings_queue ON seat_bookings (route_id, status, queued_at, id);
CREATE INDEX idx_seat_bookings_load ON seat_bookings (load_id);
CREATE UNIQUE INDEX idx_seat_bookings_payment ON seat_bookings (mpesa_payment_id) WHERE mpesa_payment_id IS NOT NULL;
