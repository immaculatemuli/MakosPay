-- A photo on a problem report (e.g. a screenshot of an M-Pesa message): on the first message
-- (message_id NULL) or on a reply. Kept in the database so backups include them. Never changed or deleted.
CREATE TABLE report_photos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id   INTEGER NOT NULL REFERENCES reports(id),
  message_id  INTEGER REFERENCES report_messages(id),
  mime_type   TEXT NOT NULL CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp')),
  data        BYTEA NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_report_photos_report ON report_photos (report_id);
