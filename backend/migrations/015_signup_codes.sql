-- Sign-up proves the phone number is the passenger's: a 6-digit code is sent to it by SMS first. Only a hash of the
-- code is kept; it works once, for 10 minutes, 5 tries. Kept per phone number (there is no account yet).
CREATE TABLE signup_codes (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone      TEXT NOT NULL,
  code_hash  TEXT NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  attempts   INTEGER NOT NULL DEFAULT 0,
  used_at    TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_signup_codes_phone ON signup_codes (phone, created_at);
