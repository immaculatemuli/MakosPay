-- Arrival updates: after a booked car leaves the stage, the conductor marks each stop as the car reaches it, then
-- the end of the trip. Passengers see where their car is, and the expected time at their stop from past trips.

-- When the conductor marked the trip as finished (the car is free to load again).
ALTER TABLE loads ADD COLUMN finished_at TIMESTAMPTZ;

-- The car reached this stop on this trip.
CREATE TABLE load_stops (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  load_id    INTEGER NOT NULL REFERENCES loads(id),
  stop_id    INTEGER NOT NULL REFERENCES route_stops(id),
  reached_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (load_id, stop_id)
);
CREATE INDEX idx_load_stops_stop ON load_stops (stop_id, reached_at);
