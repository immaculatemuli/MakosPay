-- FarePay database layout for PostgreSQL: the same 17 tables, rules and indexes as the SQLite version
-- (backend/src/db.js), in PostgreSQL types:
--   ids          INTEGER identity (plain JavaScript numbers in the app)
--   times        TIMESTAMPTZ (sent to the app in the same ISO "...Z" format as before)
--   is_active    BOOLEAN (was 0/1)
--   money        INTEGER whole Kenyan shillings, never decimals
--   audit detail JSONB
-- Applied once by scripts/migrate.js, inside a transaction. Never edit this file after it has been applied
-- anywhere: add a new numbered file instead.

-- ---------- People ----------

-- Only passengers sign up themselves; the SACCO office creates conductors and drivers; platform admins are
-- created from the server. Vehicle owners don't log in (their payout details are on the vehicle).
CREATE TABLE users (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            TEXT NOT NULL,
  phone           TEXT NOT NULL UNIQUE,
  password_hash   TEXT NOT NULL,
  role            TEXT NOT NULL CHECK (role IN ('admin', 'passenger', 'conductor', 'driver', 'platform_admin')),
  is_active       BOOLEAN NOT NULL DEFAULT TRUE,
  -- Raised when the password changes, so every older sign-in stops working.
  session_version INTEGER NOT NULL DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Routes, stops and vehicles ----------

CREATE TABLE routes (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  origin     TEXT NOT NULL,
  is_active  BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Each drop-off stop has its own cash fare and (lower or equal) FarePay member fare.
CREATE TABLE route_stops (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_id   INTEGER NOT NULL REFERENCES routes(id),
  name       TEXT NOT NULL,
  cash_fare  INTEGER NOT NULL CHECK (cash_fare > 0),
  app_fare   INTEGER NOT NULL CHECK (app_fare > 0),
  position   INTEGER NOT NULL DEFAULT 0,
  is_active  BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (app_fare <= cash_fare)
);
CREATE INDEX idx_route_stops_route ON route_stops (route_id, position);

-- A matatu: its QR token, crew, route and the owner's payout details.
CREATE TABLE vehicles (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plate               TEXT NOT NULL UNIQUE,
  description         TEXT,
  owner_name          TEXT NOT NULL,
  owner_phone         TEXT NOT NULL,
  owner_payout_method TEXT NOT NULL DEFAULT 'mpesa' CHECK (owner_payout_method IN ('mpesa', 'bank')),
  owner_bank_name     TEXT,
  owner_bank_paybill  TEXT,
  owner_bank_account  TEXT,
  conductor_id        INTEGER UNIQUE REFERENCES users(id),
  driver_id           INTEGER REFERENCES users(id),
  route_id            INTEGER REFERENCES routes(id),
  qr_token            TEXT NOT NULL UNIQUE,
  is_active           BOOLEAN NOT NULL DEFAULT TRUE,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- One driver per vehicle (as well as one conductor).
CREATE UNIQUE INDEX idx_vehicles_driver ON vehicles (driver_id) WHERE driver_id IS NOT NULL;

-- Fare changes, scheduled for a date or immediate; the old fares are recorded when one takes effect.
CREATE TABLE fare_changes (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stop_id        INTEGER NOT NULL REFERENCES route_stops(id),
  old_cash_fare  INTEGER NOT NULL,
  old_app_fare   INTEGER NOT NULL,
  new_cash_fare  INTEGER NOT NULL CHECK (new_cash_fare > 0),
  new_app_fare   INTEGER NOT NULL CHECK (new_app_fare > 0),
  effective_from TIMESTAMPTZ NOT NULL,
  applied_at     TIMESTAMPTZ,
  cancelled_at   TIMESTAMPTZ,
  reason         TEXT,
  changed_by     INTEGER NOT NULL REFERENCES users(id),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (new_app_fare <= new_cash_fare)
);
CREATE INDEX idx_fare_changes_stop ON fare_changes (stop_id, id);
CREATE INDEX idx_fare_changes_due ON fare_changes (effective_from) WHERE applied_at IS NULL AND cancelled_at IS NULL;

-- Drop-off stops a passenger saved for quick choosing.
CREATE TABLE saved_stops (
  user_id    INTEGER NOT NULL REFERENCES users(id),
  stop_id    INTEGER NOT NULL REFERENCES route_stops(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, stop_id)
);

-- ---------- Wallets ----------

-- A passenger's balance. It can never go below zero, and every change is in wallet_transactions.
CREATE TABLE wallets (
  user_id    INTEGER PRIMARY KEY REFERENCES users(id),
  balance    INTEGER NOT NULL DEFAULT 0 CHECK (balance >= 0),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- The wallet history: positive = money in, negative = money out, with the balance after each entry.
CREATE TABLE wallet_transactions (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER NOT NULL REFERENCES users(id),
  type          TEXT NOT NULL CHECK (type IN ('topup', 'fare', 'refund', 'test_credit', 'withdrawal', 'withdrawal_reversal')),
  amount        INTEGER NOT NULL,
  balance_after INTEGER NOT NULL,
  reference     TEXT,
  description   TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_wallet_tx_user ON wallet_transactions (user_id, id);

-- ---------- Owner payouts ----------

-- Money sent to a vehicle owner (M-Pesa or bank). If it fails, its fares become unpaid again.
CREATE TABLE payouts (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_name         TEXT NOT NULL,
  owner_phone        TEXT NOT NULL,
  amount             INTEGER NOT NULL CHECK (amount > 0),
  trip_count         INTEGER NOT NULL,
  -- processing: sent to M-Pesa, waiting for the result. manual: the office sends the money itself.
  status             TEXT NOT NULL CHECK (status IN ('processing', 'manual', 'completed', 'failed')),
  method             TEXT NOT NULL DEFAULT 'mpesa' CHECK (method IN ('mpesa', 'bank')),
  bank_name          TEXT,
  bank_paybill       TEXT,
  bank_account       TEXT,
  conversation_id    TEXT NOT NULL UNIQUE,
  provider_reference TEXT,
  reference          TEXT,
  result_desc        TEXT,
  created_by         INTEGER REFERENCES users(id),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at       TIMESTAMPTZ
);

-- ---------- Fares paid ----------

-- A paid fare. The owner's details are copied from the vehicle at the time, so the right person is paid.
CREATE TABLE trips (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_code     TEXT NOT NULL UNIQUE,
  passenger_id    INTEGER NOT NULL REFERENCES users(id),
  vehicle_id      INTEGER NOT NULL REFERENCES vehicles(id),
  route_id        INTEGER NOT NULL REFERENCES routes(id),
  stop_id         INTEGER REFERENCES route_stops(id),
  stop_name       TEXT,
  conductor_id    INTEGER REFERENCES users(id),
  owner_name      TEXT NOT NULL,
  owner_phone     TEXT NOT NULL,
  fare            INTEGER NOT NULL,
  cash_fare       INTEGER NOT NULL,
  idempotency_key TEXT NOT NULL,
  status          TEXT NOT NULL DEFAULT 'paid' CHECK (status IN ('paid', 'refunded')),
  refunded_at     TIMESTAMPTZ,
  refund_reason   TEXT,
  payout_id       INTEGER REFERENCES payouts(id),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- The same payment confirmation can never charge twice.
  UNIQUE (passenger_id, idempotency_key)
);
CREATE INDEX idx_trips_vehicle ON trips (vehicle_id, created_at);
CREATE INDEX idx_trips_passenger ON trips (passenger_id, id);
CREATE INDEX idx_trips_unpaid ON trips (owner_phone) WHERE payout_id IS NULL;

-- A refund made after the fare was already paid out: taken off the owner's next payout.
CREATE TABLE owner_deductions (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_phone TEXT NOT NULL,
  amount      INTEGER NOT NULL CHECK (amount > 0),
  trip_id     INTEGER NOT NULL REFERENCES trips(id),
  payout_id   INTEGER REFERENCES payouts(id),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- M-Pesa ----------

-- Every M-Pesa PIN prompt sent to a passenger: a wallet top-up or one fare paid directly.
-- Money is only credited once M-Pesa confirms.
CREATE TABLE mpesa_payments (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id             INTEGER NOT NULL REFERENCES users(id),
  phone               TEXT NOT NULL,
  amount              INTEGER NOT NULL CHECK (amount > 0),
  purpose             TEXT NOT NULL CHECK (purpose IN ('wallet', 'fare')),
  status              TEXT NOT NULL CHECK (status IN ('initiating', 'pending', 'completed', 'failed')),
  checkout_request_id TEXT UNIQUE,
  merchant_request_id TEXT,
  mpesa_receipt       TEXT,
  result_desc         TEXT,
  last_queried_at     TIMESTAMPTZ,
  vehicle_id          INTEGER REFERENCES vehicles(id),
  stop_id             INTEGER REFERENCES route_stops(id),
  idempotency_key     TEXT,
  trip_id             INTEGER REFERENCES trips(id),
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at        TIMESTAMPTZ
);
CREATE INDEX idx_mpesa_payments_status ON mpesa_payments (status);
-- One M-Pesa receipt can only ever be recorded on one payment, so the same money can't be credited twice.
CREATE UNIQUE INDEX idx_mpesa_payments_receipt ON mpesa_payments (mpesa_receipt) WHERE mpesa_receipt IS NOT NULL;

-- A passenger taking wallet money back to their own M-Pesa number.
CREATE TABLE withdrawals (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id            INTEGER NOT NULL REFERENCES users(id),
  phone              TEXT NOT NULL,
  amount             INTEGER NOT NULL CHECK (amount > 0),
  status             TEXT NOT NULL CHECK (status IN ('processing', 'manual', 'completed', 'failed')),
  conversation_id    TEXT NOT NULL UNIQUE,
  provider_reference TEXT,
  reference          TEXT,
  result_desc        TEXT,
  handled_by         INTEGER REFERENCES users(id),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at       TIMESTAMPTZ
);
CREATE INDEX idx_withdrawals_user ON withdrawals (user_id, id);
CREATE INDEX idx_withdrawals_status ON withdrawals (status);

-- ---------- Reports, notifications, audit, jobs ----------

CREATE TABLE reports (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id INTEGER NOT NULL REFERENCES users(id),
  category    TEXT NOT NULL CHECK (category IN ('payment_problem', 'wrong_fare', 'duplicate_charge', 'wrong_route', 'other')),
  trip_id     INTEGER REFERENCES trips(id),
  message     TEXT NOT NULL,
  status      TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'in_progress', 'resolved')),
  office_note TEXT,
  handled_by  INTEGER REFERENCES users(id),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_reports_status ON reports (status, id);
CREATE INDEX idx_reports_reporter ON reports (reporter_id, id);

CREATE TABLE notifications (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id),
  kind       TEXT NOT NULL,
  title      TEXT NOT NULL,
  body       TEXT,
  target     TEXT,
  read_at    TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notifications_user ON notifications (user_id, id);

-- Who did what, when. Entries can only be added: changing, deleting or emptying the log is refused.
CREATE TABLE audit_log (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id   INTEGER REFERENCES users(id),
  actor_role TEXT,
  action     TEXT NOT NULL,
  entity     TEXT,
  entity_id  INTEGER,
  details    JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_log_entity ON audit_log (entity, entity_id);

CREATE FUNCTION audit_log_read_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'audit log entries cannot be changed or deleted';
END;
$$;
CREATE TRIGGER audit_log_no_change BEFORE UPDATE OR DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION audit_log_read_only();
CREATE TRIGGER audit_log_no_truncate BEFORE TRUNCATE ON audit_log FOR EACH STATEMENT EXECUTE FUNCTION audit_log_read_only();

-- Last run date (Kenyan, YYYY-MM-DD) of each daily job, so a restart never runs a daily job twice.
CREATE TABLE job_runs (
  name     TEXT PRIMARY KEY,
  last_run TEXT NOT NULL CHECK (last_run ~ '^\d{4}-\d{2}-\d{2}$')
);
