-- Seat booking: passengers book and pay for seats on the next car loading at the stage of their route.

-- How many passengers each vehicle carries (the office sets it; 14 for a matatu by default).
ALTER TABLE vehicles ADD COLUMN seats INTEGER NOT NULL DEFAULT 14 CHECK (seats BETWEEN 1 AND 80);

-- A car loading passengers at its route's stage. The conductor starts it, and marks it as left once it leaves.
-- New bookings go to the earliest car still loading on the route with seats left.
CREATE TABLE loads (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id  INTEGER NOT NULL REFERENCES vehicles(id),
  route_id    INTEGER NOT NULL REFERENCES routes(id),
  seats       INTEGER NOT NULL CHECK (seats > 0),
  status      TEXT NOT NULL DEFAULT 'loading' CHECK (status IN ('loading', 'departed')),
  started_by  INTEGER REFERENCES users(id),
  started_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  departed_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX idx_loads_one_loading_per_vehicle ON loads (vehicle_id) WHERE status = 'loading';
CREATE INDEX idx_loads_route_status ON loads (route_id, status, started_at);

-- A booked (and paid, or being paid) seat or seats on one loading car. The money goes through the normal fare
-- payment (mpesa_payments, then a trip on the vehicle), so payouts, refunds and the money check include it.
CREATE TABLE bookings (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             TEXT NOT NULL UNIQUE,
  load_id          INTEGER NOT NULL REFERENCES loads(id),
  passenger_id     INTEGER NOT NULL REFERENCES users(id),
  stop_id          INTEGER NOT NULL REFERENCES route_stops(id),
  seats            INTEGER NOT NULL CHECK (seats BETWEEN 1 AND 10),
  fare_each        INTEGER NOT NULL CHECK (fare_each > 0),
  amount           INTEGER NOT NULL CHECK (amount > 0),
  mpesa_payment_id INTEGER REFERENCES mpesa_payments(id),
  idempotency_key  TEXT NOT NULL,
  boarded_at       TIMESTAMPTZ,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (passenger_id, idempotency_key)
);
CREATE INDEX idx_bookings_load ON bookings (load_id);
