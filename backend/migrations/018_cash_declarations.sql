-- Cash the crew say they collected on a car in a day, entered once (and corrected) by the conductor or driver. It is
-- only what they declare: it never touches wallets, payouts or the money check, and is shown beside FarePay money.
CREATE TABLE cash_declarations (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id  INTEGER NOT NULL REFERENCES vehicles(id),
  day         TEXT NOT NULL CHECK (day ~ '^\d{4}-\d{2}-\d{2}$'),
  amount      INTEGER NOT NULL CHECK (amount >= 0),
  declared_by INTEGER NOT NULL REFERENCES users(id),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (vehicle_id, day)
);
